use std::path::PathBuf;

use serde::{Deserialize, Serialize};

/// Which integration produced an action.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentKind {
    /// Claude Code `PreToolUse` hook.
    Claude,
    /// Cursor `beforeShellExecution` / `beforeMCPExecution` / `beforeReadFile` hooks.
    Cursor,
    /// Codex hook (same stdin/stdout protocol as Claude Code).
    Codex,
    /// Any MCP client going through `agent-shield mcp-proxy`.
    Mcp,
    /// A PATH shim started by `agent-shield run`.
    Shim,
}

impl AgentKind {
    /// Stable wire name of the agent kind.
    pub fn as_str(self) -> &'static str {
        match self {
            AgentKind::Claude => "claude",
            AgentKind::Cursor => "cursor",
            AgentKind::Codex => "codex",
            AgentKind::Mcp => "mcp",
            AgentKind::Shim => "shim",
        }
    }
}

/// Who is asking, and in what situation. Every [`Action`](super::Action)
/// carries one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AgentContext {
    /// The integration that intercepted the action.
    pub agent: AgentKind,
    /// Opaque session identifier supplied by the agent (or generated by the
    /// shim). Used for the session allow-cache and the audit log.
    pub session_id: String,
    /// Working directory of the agent session; the workspace boundary for
    /// "outside the workspace" rules.
    pub cwd: PathBuf,
    /// `true` when no human is available to answer an Ask. The policy
    /// `defaults.on_no_ui` then decides, and the default is deny.
    pub autonomous: bool,
}
